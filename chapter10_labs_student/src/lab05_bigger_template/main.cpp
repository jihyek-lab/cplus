#include <iostream>
using namespace std;

/*
[Lab05] bigger<T>: 비교 연산(>)이 가능한 타입만 사용 가능
------------------------------------------------------------
- 템플릿 내부에서 a > b를 쓰면,
  T 타입이 operator>를 지원해야 한다.
- 기본 타입은 OK.
- 사용자 정의 타입이면 7장의 operator> 오버로딩이 필요할 수 있다.

이론 연결
- 템플릿은 겉보기에는 모든 타입에 되는 것처럼 보이지만,
  실제로는 내부 코드가 요구하는 연산을 지원하는 타입에만 사용할 수 있다.
- 이런 숨은 조건을 템플릿의 "암묵적 제약"으로 이해하면 좋다.
------------------------------------------------------------
*/

template <class T>
T bigger(T a, T b) {
    return (a > b) ? a : b;
}

int main() {
    int a=20, b=50;
    char c='a', d='z';
    cout << bigger(a,b) << "\n";
    cout << bigger(c,d) << "\n";
}
